/**
 * 2,000 and 50,000 characters each have two factor pairs (25×80 vs 40×50,
 * and 200×250 vs 125×400) whose pixel aspect ratios are exact reciprocals
 * of one another — e.g. 800×500 (aspect 1.6) and 500×800 (aspect 0.625)
 * are equally "close to square" in log-space. The source table picks one
 * side of that tie; the engine's stable first-found tie-break picks the
 * other. Both are equally valid zero-waste layouts (and, as verified
 * below, cost the same vision tokens), so these two rows are checked for
 * tied-optimality rather than an exact column/row match.
 */
const KNOWN_ASPECT_TIES = new Set([2000, 50000])

describe('exactResolution — golden table (1,000 to 100,000 characters)', () => {
  it.each(EXACT_FIT_TABLE)(
    '%i characters',
    (characters, textTokens, columns, rows, width, height, imageTokens) => {
      expect(estimateTextTokens(characters)).toBe(textTokens)

      const result = exactResolution(characters, { width: 10, height: 20 })
      expect(result.columns * result.rows).toBe(characters)
      expect(result.unusedCells).toBe(0)
      expect(Math.ceil(result.width / 32) * Math.ceil(result.height / 32)).toBe(imageTokens)

      if (KNOWN_ASPECT_TIES.has(characters)) {
        const tableScore = Math.abs(Math.log(width / height))
        const engineScore = Math.abs(Math.log(result.width / result.height))
        expect(engineScore).toBeCloseTo(tableScore, 10)
        return
      }

      expect(result.columns).toBe(columns)
      expect(result.rows).toBe(rows)
      expect(result.width).toBe(width)
      expect(result.height).toBe(height)
    },
  )
})
